def _typo(text: str, rng: random.Random) -> str:
    words = text.split()
    for _ in range(2):
        i = rng.randrange(len(words))
        w = words[i]
        if len(w) > 4:
            j = rng.randrange(1, len(w) - 1)
            words[i] = w[:j] + w[j + 1:]
    return " ".join(words)


def _order(text: str) -> str:
    parts = [p.strip() for p in text.replace("—", ",").split(",") if p.strip()]
    if len(parts) < 3:
        return text
    return ", ".join([parts[0], *reversed(parts[1:])])


VARIANTS = {
    "exact": lambda t, r: "  " + t.upper().replace(",", " ,") + "!!",
    "typo": _typo,
    "extra": lambda t, r: t + " Не забыть.",
    "order": lambda t, r: _order(t),
    "sign": lambda t, r: "Напоминалка: " + t,
    "para": lambda t, r: t + "\nP.S. Обсудили с мужем вечером, всё в силе.",
}


def build(seed: int = 7, repeats: tuple[str, ...] = ("exact", "typo", "extra", "order", "sign",
                                                    "para")) -> list[Rec]:  # fmt: skip
    rng = random.Random(seed)
    out: list[Rec] = []
    cluster = 0

    def add(c: int, kind: str, text: str) -> None:
        out.append(Rec(len(out) + 1, c, kind, text))

    for base in BASES:
        cluster += 1
        add(cluster, "base", base)
        for kind in rng.sample(list(repeats), k=min(len(repeats), rng.randint(1, 3))):
            add(cluster, kind, VARIANTS[kind](base, rng))
    for a, b in NEGATIVE_PAIRS:
        cluster += 1
        add(cluster, "base", a)
        cluster += 1
        add(cluster, "base", b)
    return out


def truth_pairs(recs: list[Rec], *, without_exact: bool = True) -> set[tuple[int, int]]:
    out = set()
    for i, a in enumerate(recs):
        for b in recs[i + 1:]:
            if a.cluster == b.cluster and not (without_exact and "exact" in (a.kind, b.kind)
                                               and {a.kind, b.kind} <= {"base", "exact"}):
                out.add((a.id, b.id))
    return out
